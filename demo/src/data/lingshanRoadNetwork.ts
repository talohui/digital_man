const ROAD_NETWORK_SKIPPED: LingshanRoadNetwork['skipped'] = []

function resolveRoadNetworkNode(poiId: string): RoadNetworkNode | null {
  const poi = lingshanPois.find((item) => item.id === poiId)
  if (poi) {
    return {
      id: poi.id,
      name: poi.name,
      kind: 'poi',
      location: poi.navLocation ?? poi.displayLocation,
      source: 'poi'
    }
  }

  const guideSpot = guideSpots.find((item) => item.id === poiId)
  if (guideSpot) {
    return {
      id: guideSpot.id,
      name: guideSpot.name,
      kind: 'poi',
      location: { lat: guideSpot.lat, lng: guideSpot.lng },
      source: 'poi'
    }
  }

  return null
}

function buildRoadNetworkNodes(segments: RoadNetworkSegment[]): RoadNetworkNode[] {
  const poiIds = Array.from(new Set(segments.flatMap((segment) => [segment.fromPoiId, segment.toPoiId])))
  return poiIds
    .map((poiId) => resolveRoadNetworkNode(poiId))
    .filter((node): node is RoadNetworkNode => Boolean(node))
}

