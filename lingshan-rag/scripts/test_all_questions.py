def run_tests():
    total = len(TEST_CASES)
    passed = 0
    faq_hit = 0
    llm_used = 0
    refused = 0
    failed_cases = []

    category_stats = {}

    print("=" * 70)
    print(f"灵山 RAG 全量测试  共 {total} 题")
    print("=" * 70)

    for category, question, expected_keywords in TEST_CASES:
        result = answer_question(question, top_k=5, use_llm=True)
        answer = result["answer"]
        is_faq = result["faq"] is not None
        is_llm = result["used_llm"]
        is_refused = "超出" in answer or "不能确定" in answer or "暂时" in answer

        # 判断是否命中
        hit = any(kw in answer for kw in expected_keywords)

        if is_faq:
            faq_hit += 1
        if is_llm:
            llm_used += 1
        if is_refused:
            refused += 1
        if hit:
            passed += 1

        # 分类统计
        if category not in category_stats:
            category_stats[category] = {"total": 0, "passed": 0}
        category_stats[category]["total"] += 1
        if hit:
            category_stats[category]["passed"] += 1

        # 输出
        status = "✓" if hit else "✗"
        source = "FAQ" if is_faq else ("LLM" if is_llm else "本地")
        print(f"\n[{status}] [{category}] [{source}] {question}")
        if not hit:
            # 截断显示答案
            short_answer = answer.replace("\n", " ")[:120]
            print(f"    期望含: {expected_keywords}")
            print(f"    实际答: {short_answer}...")
            failed_cases.append((category, question, expected_keywords, answer))

    # ── 汇总 ──────────────────────────────────
    print("\n" + "=" * 70)
    print("分类统计")
    print("=" * 70)
    for cat, stat in category_stats.items():
        rate = stat["passed"] / stat["total"] * 100
        bar = "█" * stat["passed"] + "░" * (stat["total"] - stat["passed"])
        print(f"  {cat:8s} {bar}  {stat['passed']}/{stat['total']} ({rate:.0f}%)")

    print("\n" + "=" * 70)
    print(f"总体结果:  {passed}/{total}  通过率 {passed/total*100:.1f}%")
    print(f"  FAQ命中: {faq_hit} 题  |  LLM生成: {llm_used} 题  |  本地模板: {total-faq_hit-llm_used} 题")
    print(f"  触发拒答: {refused} 题")

    if failed_cases:
        print("\n" + "=" * 70)
        print(f"失败题目详情 ({len(failed_cases)} 题)")
        print("=" * 70)
        for cat, q, kws, ans in failed_cases:
            print(f"\n[{cat}] {q}")
            print(f"  期望关键词: {kws}")
            wrapped = textwrap.fill(ans.replace("\n", " "), width=80, initial_indent="  答案: ", subsequent_indent="        ")
            print(wrapped)

    return passed, total


if __name__ == "__main__":
    passed, total = run_tests()
    sys.exit(0 if passed / total >= 0.75 else 1)
